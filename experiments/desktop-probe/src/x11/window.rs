use x11rb::connection::Connection;
use x11rb::protocol::xproto::{
    AtomEnum, Colormap, ColormapAlloc, ConfigureNotifyEvent, ConfigureWindowAux,
    ConnectionExt as XprotoExt, CreateWindowAux, EventMask, PropMode, Visualid, Window,
    WindowClass,
};
use x11rb::wrapper::ConnectionExt as WrapperExt;

use super::render::{WINDOW_HEIGHT, WINDOW_WIDTH};
use super::shape::apply_body_input_shape;
use crate::geometry::{Point, Rect, Size};

/// Outcomes of reconciling a ConfigureNotify event.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ConfigureReconciliation {
    /// Window configuration matches expected dimensions and requested origin.
    Confirmed { origin: Point, size: Size },
    /// Position differs between requested and confirmed coordinates.
    PositionMismatch { requested: Point, confirmed: Point },
    /// Unexpected size change from window manager.
    UnexpectedSizeChange { expected: Size, actual: Size },
}

/// Detailed classification of an incoming ConfigureNotify event.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ConfigureEventAnalysis {
    /// Event was sent by WM via SendEvent; coordinates are in root space.
    SyntheticRootOrigin { origin: Point, size: Size },
    /// Event was generated by server; coordinates are parent-relative and require translation.
    RequiresRootTranslation {
        parent_relative_x: i16,
        parent_relative_y: i16,
        size: Size,
    },
    /// Window dimensions differ from expected fixed size.
    UnexpectedSizeChange { expected: Size, actual: Size },
}

pub struct ManagedProbeWindow {
    pub window: Window,
    pub colormap: Colormap,
    pub wm_delete_window: u32,
    pub requested_origin: Point,
    pub confirmed_origin: Point,
    pub width: u16,
    pub height: u16,
}

impl ManagedProbeWindow {
    pub fn create(
        conn: &impl Connection,
        root: Window,
        visual_id: Visualid,
        initial_origin: Point,
    ) -> Result<Self, Box<dyn std::error::Error>> {
        // 1. Create a colormap for the 32-bit visual (required in X11 to prevent BadMatch)
        let colormap = conn.generate_id()?;
        conn.create_colormap(ColormapAlloc::NONE, colormap, root, visual_id)?
            .check()?;

        // 2. Position the window at initial_origin on the primary display
        let width = WINDOW_WIDTH;
        let height = WINDOW_HEIGHT;
        let x = initial_origin.x;
        let y = initial_origin.y;

        // 3. Create the managed 32-bit window (override_redirect is false by default)
        // Request exposure, structure, and mouse pointer events (enter, leave, button clicks)
        let window = conn.generate_id()?;
        let win_aux = CreateWindowAux::new()
            .background_pixel(0)
            .border_pixel(0)
            .colormap(colormap)
            .event_mask(
                EventMask::EXPOSURE
                    | EventMask::STRUCTURE_NOTIFY
                    | EventMask::ENTER_WINDOW
                    | EventMask::LEAVE_WINDOW
                    | EventMask::BUTTON_PRESS
                    | EventMask::BUTTON_RELEASE,
            );

        conn.create_window(
            32, // depth
            window,
            root,
            x as i16,
            y as i16,
            width,
            height,
            0, // border_width
            WindowClass::INPUT_OUTPUT,
            visual_id,
            &win_aux,
        )?
        .check()?;

        // Set WM_NORMAL_HINTS (UserSpecified position and size) to direct Openbox placement
        let mut size_hints = x11rb::properties::WmSizeHints::new();
        size_hints.position = Some((
            x11rb::properties::WmSizeHintsSpecification::UserSpecified,
            x,
            y,
        ));
        size_hints.size = Some((
            x11rb::properties::WmSizeHintsSpecification::UserSpecified,
            width as i32,
            height as i32,
        ));
        size_hints.min_size = Some((width as i32, height as i32));
        size_hints.max_size = Some((width as i32, height as i32));
        size_hints.set_normal_hints(conn, window)?.check()?;

        // Set WM_HINTS: explicitly request no keyboard focus (ICCCM No-Input model)
        let mut wm_hints = x11rb::properties::WmHints::new();
        wm_hints.input = Some(false);
        wm_hints.set(conn, window)?.check()?;

        // 4. Motif hints: borderless (decorations = 0)
        let motif_atom = conn.intern_atom(false, b"_MOTIF_WM_HINTS")?.reply()?.atom;
        // flags = 2 (MWM_HINTS_DECORATIONS), decorations = 0
        let motif_hints = [2u32, 0, 0, 0, 0];
        conn.change_property32(
            PropMode::REPLACE,
            window,
            motif_atom,
            motif_atom,
            &motif_hints,
        )?
        .check()?;

        // 5. EWMH Window Type: UTILITY (non-disruptive desktop element)
        let net_wm_window_type = conn
            .intern_atom(false, b"_NET_WM_WINDOW_TYPE")?
            .reply()?
            .atom;
        let net_wm_window_type_utility = conn
            .intern_atom(false, b"_NET_WM_WINDOW_TYPE_UTILITY")?
            .reply()?
            .atom;
        conn.change_property32(
            PropMode::REPLACE,
            window,
            net_wm_window_type,
            AtomEnum::ATOM,
            &[net_wm_window_type_utility],
        )?
        .check()?;

        // 6. Set WM_PROTOCOLS: WM_DELETE_WINDOW (clean graceful close; omits WM_TAKE_FOCUS)
        let wm_protocols = conn.intern_atom(false, b"WM_PROTOCOLS")?.reply()?.atom;
        let wm_delete_window = conn.intern_atom(false, b"WM_DELETE_WINDOW")?.reply()?.atom;
        conn.change_property32(
            PropMode::REPLACE,
            window,
            wm_protocols,
            AtomEnum::ATOM,
            &[wm_delete_window],
        )?
        .check()?;

        // EWMH _NET_WM_USER_TIME = 0: explicitly informs window manager not to take focus on map
        let net_wm_user_time = conn.intern_atom(false, b"_NET_WM_USER_TIME")?.reply()?.atom;
        conn.change_property32(
            PropMode::REPLACE,
            window,
            net_wm_user_time,
            AtomEnum::CARDINAL,
            &[0],
        )?
        .check()?;

        // 7. Set window title and class
        conn.change_property8(
            PropMode::REPLACE,
            window,
            AtomEnum::WM_NAME,
            AtomEnum::STRING,
            b"DesktopRoomie-Probe",
        )?
        .check()?;
        conn.change_property8(
            PropMode::REPLACE,
            window,
            AtomEnum::WM_CLASS,
            AtomEnum::STRING,
            b"desktop-probe\0DesktopRoomie\0",
        )?
        .check()?;

        // 8. Apply X11 Shape extension: restrict pointer input exclusively to the test shapes
        apply_body_input_shape(conn, window, width, height)?;

        // 9. Map window to screen
        conn.map_window(window)?.check()?;
        conn.flush()?;

        let requested_origin = initial_origin;
        let confirmed_origin = initial_origin;

        Ok(Self {
            window,
            colormap,
            wm_delete_window,
            requested_origin,
            confirmed_origin,
            width,
            height,
        })
    }

    pub fn x(&self) -> i32 {
        self.confirmed_origin.x
    }

    pub fn y(&self) -> i32 {
        self.confirmed_origin.y
    }

    pub fn requested_origin(&self) -> Point {
        self.requested_origin
    }

    pub fn confirmed_origin(&self) -> Point {
        self.confirmed_origin
    }

    /// Sends a position-only ConfigureWindow request to move the window.
    /// Preserves width, height, visual, shape, and hints.
    /// The request is issued asynchronously without blocking on server round-trips.
    pub fn configure_position(
        &mut self,
        conn: &impl Connection,
        target: Point,
    ) -> Result<(), Box<dyn std::error::Error>> {
        let aux = ConfigureWindowAux::new().x(target.x).y(target.y);
        conn.configure_window(self.window, &aux)?;
        self.requested_origin = target;
        Ok(())
    }

    /// Evaluates a ConfigureNotify event to determine whether coordinates are synthetic (root space)
    /// and whether dimensions match expectations.
    pub fn evaluate_configure_event(
        expected_size: Size,
        ev: &ConfigureNotifyEvent,
    ) -> ConfigureEventAnalysis {
        let actual_size = Size::new(ev.width as u32, ev.height as u32);
        if actual_size != expected_size {
            return ConfigureEventAnalysis::UnexpectedSizeChange {
                expected: expected_size,
                actual: actual_size,
            };
        }

        let is_synthetic = (ev.response_type & 0x80) != 0;
        if is_synthetic {
            ConfigureEventAnalysis::SyntheticRootOrigin {
                origin: Point::new(ev.x as i32, ev.y as i32),
                size: actual_size,
            }
        } else {
            ConfigureEventAnalysis::RequiresRootTranslation {
                parent_relative_x: ev.x,
                parent_relative_y: ev.y,
                size: actual_size,
            }
        }
    }

    /// Reconciles actual root geometry upon receiving a ConfigureNotify event.
    ///
    /// Distinguishes ICCCM synthetic events from the WM (where `response_type & 0x80 != 0`
    /// indicates root coordinates) from server-generated structure events (where coordinates
    /// are parent-relative and must be translated to root space).
    pub fn handle_configure_notify(
        &mut self,
        conn: &impl Connection,
        root: Window,
        ev: &ConfigureNotifyEvent,
    ) -> Result<ConfigureReconciliation, Box<dyn std::error::Error>> {
        let analysis =
            Self::evaluate_configure_event(Size::new(self.width as u32, self.height as u32), ev);

        match analysis {
            ConfigureEventAnalysis::UnexpectedSizeChange { expected, actual } => {
                Ok(ConfigureReconciliation::UnexpectedSizeChange { expected, actual })
            }
            ConfigureEventAnalysis::SyntheticRootOrigin { origin, size } => {
                self.confirmed_origin = origin;
                if origin != self.requested_origin {
                    Ok(ConfigureReconciliation::PositionMismatch {
                        requested: self.requested_origin,
                        confirmed: origin,
                    })
                } else {
                    Ok(ConfigureReconciliation::Confirmed { origin, size })
                }
            }
            ConfigureEventAnalysis::RequiresRootTranslation { size, .. } => {
                let origin = self.query_actual_root_origin(conn, root)?;
                self.confirmed_origin = origin;
                if origin != self.requested_origin {
                    Ok(ConfigureReconciliation::PositionMismatch {
                        requested: self.requested_origin,
                        confirmed: origin,
                    })
                } else {
                    Ok(ConfigureReconciliation::Confirmed { origin, size })
                }
            }
        }
    }

    /// Queries the window's actual root-coordinate origin using X11 `TranslateCoordinates`.
    /// When managed by a window manager, the client window may be reparented into a WM frame,
    /// so client-window coordinates relative to parent may differ from root coordinates.
    pub fn query_actual_root_origin(
        &self,
        conn: &impl Connection,
        root: Window,
    ) -> Result<Point, Box<dyn std::error::Error>> {
        let reply = conn
            .translate_coordinates(self.window, root, 0, 0)?
            .reply()?;
        Ok(Point::new(reply.dst_x as i32, reply.dst_y as i32))
    }

    /// Queries the window's actual root-coordinate origin and size.
    pub fn query_actual_root_geometry(
        &mut self,
        conn: &impl Connection,
        root: Window,
    ) -> Result<Rect, Box<dyn std::error::Error>> {
        let origin = self.query_actual_root_origin(conn, root)?;
        self.confirmed_origin = origin;
        let geom = conn.get_geometry(self.window)?.reply()?;
        Ok(Rect::new(
            origin.x,
            origin.y,
            geom.width as u32,
            geom.height as u32,
        ))
    }

    /// Releases server-side Window and Colormap resources, checking requests and reporting failures
    pub fn destroy(&self, conn: &impl Connection) -> Result<(), Box<dyn std::error::Error>> {
        let mut first_error = None;

        match conn.destroy_window(self.window) {
            Ok(cookie) => {
                if let Err(e) = cookie.check() {
                    first_error = Some(Box::new(e) as Box<dyn std::error::Error>);
                }
            }
            Err(e) => {
                first_error = Some(Box::new(e) as Box<dyn std::error::Error>);
            }
        }

        match conn.free_colormap(self.colormap) {
            Ok(cookie) => {
                if let Err(e) = cookie.check() {
                    if first_error.is_none() {
                        first_error = Some(Box::new(e) as Box<dyn std::error::Error>);
                    }
                }
            }
            Err(e) => {
                if first_error.is_none() {
                    first_error = Some(Box::new(e) as Box<dyn std::error::Error>);
                }
            }
        }

        if let Err(e) = conn.flush() {
            if first_error.is_none() {
                first_error = Some(Box::new(e) as Box<dyn std::error::Error>);
            }
        }

        if let Some(err) = first_error {
            Err(err)
        } else {
            Ok(())
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::geometry::Size;

    #[test]
    fn test_evaluate_configure_event_synthetic() {
        let ev = ConfigureNotifyEvent {
            response_type: 0x80 | 22,
            sequence: 1,
            event: 100,
            window: 100,
            above_sibling: 0,
            x: 250,
            y: 350,
            width: 160,
            height: 160,
            border_width: 0,
            override_redirect: false,
        };
        let analysis = ManagedProbeWindow::evaluate_configure_event(Size::new(160, 160), &ev);
        assert_eq!(
            analysis,
            ConfigureEventAnalysis::SyntheticRootOrigin {
                origin: Point::new(250, 350),
                size: Size::new(160, 160),
            }
        );
    }

    #[test]
    fn test_evaluate_configure_event_server_structure() {
        let ev = ConfigureNotifyEvent {
            response_type: 22, // not synthetic
            sequence: 1,
            event: 100,
            window: 100,
            above_sibling: 0,
            x: 0,
            y: 0,
            width: 160,
            height: 160,
            border_width: 0,
            override_redirect: false,
        };
        let analysis = ManagedProbeWindow::evaluate_configure_event(Size::new(160, 160), &ev);
        assert_eq!(
            analysis,
            ConfigureEventAnalysis::RequiresRootTranslation {
                parent_relative_x: 0,
                parent_relative_y: 0,
                size: Size::new(160, 160),
            }
        );
    }

    #[test]
    fn test_evaluate_configure_event_unexpected_size() {
        let ev = ConfigureNotifyEvent {
            response_type: 0x80 | 22,
            sequence: 1,
            event: 100,
            window: 100,
            above_sibling: 0,
            x: 100,
            y: 100,
            width: 320,
            height: 240,
            border_width: 0,
            override_redirect: false,
        };
        let analysis = ManagedProbeWindow::evaluate_configure_event(Size::new(160, 160), &ev);
        assert_eq!(
            analysis,
            ConfigureEventAnalysis::UnexpectedSizeChange {
                expected: Size::new(160, 160),
                actual: Size::new(320, 240),
            }
        );
    }
}
