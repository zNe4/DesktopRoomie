    #[test]
    fn test_evaluate_configure_event_synthetic() {
        let ev = ConfigureNotifyEvent {
            response_type: 0x80 | 22,
            sequence: 1,
            event: 100,
            window: 100,
            above_sibling: 0,
            x: 250,
            y: 350,
            width: 160,
            height: 160,
            border_width: 0,
            override_redirect: false,
        };
        let analysis = ManagedProbeWindow::evaluate_configure_event(Size::new(160, 160), &ev);
        assert_eq!(
            analysis,
            ConfigureEventAnalysis::SyntheticRootOrigin {
                origin: Point::new(250, 350),
                size: Size::new(160, 160),
            }
        );
    }

